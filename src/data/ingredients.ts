function classifyIngredient(name: string): IngredientGroup {
  const known = groups[name];
  if (known) return known;

  const key = name.toLowerCase().replace(/ё/g, "е");

  // «Печенье» — бакалея, «печень/печёнка» — белок.
  if (/печенье|печенюш/.test(key)) return "Бакалея";
  if (/[^а-я]печен|^печен|печень|печён/.test(key)) return "Белок";

  // Составные названия, где первый компонент не должен решать.
  if (/кокосовое молоко|молоко кокосовое/.test(key)) return "Соусы и специи";
  if (/паста томат|томатная паст|томатн/.test(key)) return "Соусы и специи";
  if (/паста.*(мисо|песто|тахини|кунжут|карри|кочуджян|устричн|рыбн)/.test(key))
    return "Соусы и специи";
  if (/сливочное масло|масло сливочное/.test(key)) return "Белок";
  if (/стручков/.test(key)) return "Овощи и зелень";
  if (/горошек/.test(key)) return "Овощи и зелень";
  if (/кукурузная мук|картофельный крахмал|рисовая мук/.test(key))
    return "Бакалея";

  // Явные соусы и приправы важнее «рыбного» или «сливового» корня.
  if (/соус|специ|приправ|уксус|майонез|кетчуп|горчиц/.test(key))
    return "Соусы и специи";
  if (/масло/.test(key)) return "Соусы и специи";

  for (const [group, keywords] of classifiers) {
    if (keywords.some((keyword) => key.includes(keyword))) return group;
  }

  return "Прочее";
}

const seen = new Set<string>();
const fromRecipes: CatalogItem[] = recipes.flatMap((recipe) =>
  recipe.ingredients.map((ingredient) => ({
    name: ingredient.name,
    group: classifyIngredient(ingredient.name),
  })),
);

export const ingredientCatalog: CatalogItem[] = [...fromRecipes, ...extras]
  .filter((item) => {
    if (seen.has(item.name)) return false;
    seen.add(item.name);
    return true;
  })
  .sort((a, b) => {
    const groupDiff =
      groupOrder.indexOf(a.group) - groupOrder.indexOf(b.group);
    return groupDiff !== 0
      ? groupDiff
      : a.name.localeCompare(b.name, "ru");
  });

export const ingredientGroups = groupOrder
  .map((group) => ({
    title: group,
    items: ingredientCatalog.filter((item) => item.group === group),
  }))
  .filter((group) => group.title !== "Прочее" && group.items.length > 0);

