function normalizeName(name: string): string {
  return name
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/[().,]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function canonicalName(name: string): string {
  const normalized = normalizeName(name);
  return aliases[normalized] ?? name.trim();
}

function buildIngredients(ingredients: SeedIngredient[]) {
  return ingredients.map(([name, amount, unit, optional]) => ({
    name: canonicalName(name),
    amount,
    unit,
    ...(optional ? { optional: true } : {}),
  }));
}

function buildSteps(seed: Seed) {
  const steps = seed.steps.map<SeedStep>((step) => step);
  const hasTimed = steps.some(
    (step) => step[2] !== undefined || step[3] !== undefined,
  );

  if (!hasTimed) {
    let index = steps.length - 1;
    while (
      index > 0 &&
      /подава|остуди|сервир|дайте/i.test(steps[index][0])
    ) {
      index -= 1;
    }
    steps[index] = [
      steps[index][0],
      steps[index][1],
      seed.temp,
      seed.time,
      steps[index][4],
    ];
  }

  return steps.map(([title, text, temp, time, tip]) => ({
    title,
    text,
    ...(temp !== undefined ? { temp } : {}),
    ...(time !== undefined ? { time } : {}),
    ...(tip ? { tip } : {}),
  }));
}

function buildTips(seed: Seed): Tip[] {
  const tips = seed.tips ?? defaultTips[seed.category];
  return tips.map(([kind, text]) => ({ kind, text }));
}

export function dualHeatFor(
  category: Category,
  noFlip: boolean,
): DualHeatProfile {
  return {
    noFlip,
    note: noFlip
      ? dualHeatNotes[category].noFlip
      : dualHeatNotes[category].flip,
  };
}

export function seedToRecipe(seed: Seed): Recipe {
  const note =
    seed.note ??
    (seed.noFlip
      ? dualHeatNotes[seed.category].noFlip
      : dualHeatNotes[seed.category].flip);

  return {
    id: seed.slug,
    slug: seed.slug,
    title: seed.title,
    subtitle: seed.subtitle,
    description: seed.description,
    country: seed.country,
    flag: seed.flag,
    cuisine: seed.cuisine,
    category: seed.category,
    difficulty: seed.difficulty,
    prepTime: seed.prepTime,
    totalTime: seed.prepTime + seed.time,
    kcal: seed.kcal,
    servings: seed.servings,
    temp: seed.temp,
    time: seed.time,
    preheat: seed.preheat ?? true,
    dualHeat: { noFlip: seed.noFlip, note },
    tags: seed.tags,
    emoji: seed.emoji,
    tone: seed.tone,
    ingredients: buildIngredients(seed.ingredients),
    steps: buildSteps(seed),
    tips: buildTips(seed),
  };
}

export function buildRecipes(seeds: Seed[]): Recipe[] {
  return seeds.map(seedToRecipe);
}
